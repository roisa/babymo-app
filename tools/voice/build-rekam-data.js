#!/usr/bin/env node
/* Builds www/tools/rekam-data.js — the clip list for the recording page (www/tools/rekam-suara.html) — from the
   clip lists in this folder (clips.json, clips-app.json, clips-lines.json). Every clip the app can play, with the
   exact file the manifests point at, so a recorded take replaces the AI clip 1:1.
     node tools/voice/build-rekam-data.js
   Run it after any of the clip lists change (build-app-clips.js / build-lines-clips.js / clips.json edits).

   Row: {id, s: page section, g: group, t: text, h: hint, l: lang (ar/id/en), k: kind, f: target file under www/,
         key: "lang|normalised text" (the www/voice/manifest.js key, same normalising as bm-voice.js)} */
const fs = require('fs'), path = require('path');
const { norm } = require('./voicekey.js');
const ROOT = path.resolve(__dirname, '..', '..');
const read = f => JSON.parse(fs.readFileSync(path.join(__dirname, f), 'utf8'));

const items = [...read('clips.json'), ...read('clips-app.json'), ...read('clips-lines.json')];
const DIR = { huruf: 'hijaiyah-voice', doa: 'doa-voice', app: 'voice', cari: 'voice', lines: 'voice' };
// page sections, in app order; Doa Ramadan is its own section (same folder as Doa Harian)
const SECTIONS = [
  { s: 'huruf', id: 'Huruf Hijaiyah', en: 'Hijaiyah letters', ic: '🔤' },
  { s: 'doa', id: 'Doa Harian', en: 'Daily du\'as', ic: '🤲' },
  { s: 'ramadan', id: 'Doa Ramadan', en: 'Ramadan du\'as', ic: '🌙' },
  { s: 'app', id: 'Arab di game', en: 'Game Arabic', ic: '🕌' },
  { s: 'cari', id: 'Cari Baby Mo', en: 'Find Baby Mo', ic: '🔍' },
  { s: 'lines', id: 'Kalimat (ID + EN)', en: 'Spoken lines (ID + EN)', ic: '💬' },
];
const seen = new Set();
const rows = items.map(x => {
  const l = x.lang || 'ar';
  if (!DIR[x.sec]) throw new Error('unknown sec ' + x.sec + ' (' + x.id + ')');
  if (!/^[A-Za-z0-9_-]+$/.test(x.id)) throw new Error('bad id ' + x.id);
  if (seen.has(x.id)) throw new Error('duplicate id ' + x.id);
  seen.add(x.id);
  const s = x.sec === 'doa' && x.g === 'Doa Ramadan' ? 'ramadan' : x.sec;
  return { id: x.id, s, g: x.g || '', t: x.t, h: x.h || '', l, k: x.k || '', f: DIR[x.sec] + '/' + x.id + '.mp3', key: l + '|' + norm(x.t, l) };
});
const order = SECTIONS.map(x => x.s);
rows.sort((a, b) => order.indexOf(a.s) - order.indexOf(b.s));   // stable: keeps list order within a section
const counts = SECTIONS.map(x => x.s + ' ' + rows.filter(r => r.s === x.s).length).join(', ');
const out = '/* Clip list for rekam-suara.html (generated by tools/voice/build-rekam-data.js from clips.json + clips-app.json +\n' +
  '   clips-lines.json; do not edit). ' + rows.length + ' clips: ' + counts + ' */\n' +
  'window.REKAM_SECTIONS=' + JSON.stringify(SECTIONS) + ';\n' +
  'window.REKAM=[\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n];\n';
fs.writeFileSync(path.join(ROOT, 'www', 'tools', 'rekam-data.js'), out);
console.log('wrote www/tools/rekam-data.js (' + rows.length + ' clips: ' + counts + ')');
